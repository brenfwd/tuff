//! Parity matrix: which vanilla registry entries the server's own code
//! mentions by name. `docs/PARITY.md` is generated from this test; rerun
//! with `TUFF_UPDATE_PARITY=1 cargo test --test server parity_matrix` after code that
//! adds or removes a registry reference, and commit the result.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use tuff_vanilla_data::registry::EntityType;
use tuff_vanilla_data::{Block, Item, Registry};

const OUTPUT: &str = "docs/PARITY.md";

fn source_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<_> = entries.flatten().map(|entry| entry.path()).collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            if path.file_name().is_some_and(|name| name != "tests") {
                source_files(&path, out);
            }
        } else if path.extension().is_some_and(|ext| ext == "rs")
            && path.file_name().is_some_and(|name| {
                let name = name.to_string_lossy();
                name != "tests.rs" && !name.ends_with("_tests.rs")
            })
        {
            out.push(path);
        }
    }
}

fn production_sources(root: &Path) -> Vec<String> {
    let mut files = Vec::new();
    source_files(&root.join("src"), &mut files);
    let mut crates: Vec<_> = fs::read_dir(root.join("crates"))
        .expect("crates dir")
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.file_name().is_some_and(|name| name != "vanilla-data"))
        .collect();
    crates.sort();
    for krate in crates {
        source_files(&krate.join("src"), &mut files);
    }
    files
        .iter()
        .filter_map(|path| fs::read_to_string(path).ok())
        .map(|text| match text.find("#[cfg(test)]") {
            Some(at) => text[..at].to_string(),
            None => text,
        })
        .collect()
}

fn mentions(sources: &[String], prefix: &str) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    for text in sources {
        let bytes = text.as_bytes();
        let mut from = 0;
        while let Some(at) = text[from..].find(prefix) {
            let start = from + at;
            let end = start + prefix.len();
            from = end;
            let boundary = start == 0 || {
                let before = bytes[start - 1];
                !(before.is_ascii_alphanumeric() || before == b'_')
            };
            if !boundary {
                continue;
            }
            let ident: String = text[end..]
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                .collect();
            if !ident.is_empty() {
                found.insert(ident);
            }
        }
    }
    found
}

fn section<R: Registry + core::fmt::Debug>(
    out: &mut String,
    title: &str,
    covered: &BTreeSet<String>,
    note: &str,
) {
    let mut missing = Vec::new();
    for entry in R::ALL {
        if !covered.contains(&format!("{entry:?}")) {
            missing.push(entry.name());
        }
    }
    let total = R::ALL.len();
    let have = total - missing.len();
    writeln!(out, "## {title}\n").unwrap();
    writeln!(out, "{note}\n").unwrap();
    writeln!(
        out,
        "{have} of {total} referenced ({:.1}%).\n",
        have as f64 * 100.0 / total as f64
    )
    .unwrap();
    if missing.is_empty() {
        writeln!(out, "Every entry is referenced.\n").unwrap();
    } else {
        writeln!(out, "Not referenced ({}):\n", missing.len()).unwrap();
        writeln!(out, "{}\n", missing.join(", ")).unwrap();
    }
}

fn render(root: &Path) -> String {
    let sources = production_sources(root);
    let mut out = String::new();
    out.push_str(
        "# Parity matrix\n\nGenerated by `tests/server/parity_matrix.rs`; do not edit. Regenerate with \
         `TUFF_UPDATE_PARITY=1 cargo test --test server parity_matrix`.\n\n\
         An entry counts as referenced when non-test server code names it (`Block::Name`, \
         `Item::Name`, `EntityType::Name`). Behavior driven only by a tag, \
         a property or generated data is not seen, so an unreferenced entry is a lead to check, \
         not proof of a gap, and a referenced one is not proof of full parity.\n\n",
    );
    section::<EntityType>(
        &mut out,
        "Entity types",
        &mentions(&sources, "EntityType::"),
        "Mobs register with `registry.register(EntityType::X, ...)`; other entities are matched in \
         their own systems.",
    );
    section::<Block>(
        &mut out,
        "Blocks",
        &mentions(&sources, "Block::"),
        "Blocks with no named reference rely on generic shape, tag and property handling only.",
    );
    section::<Item>(
        &mut out,
        "Items",
        &mentions(&sources, "Item::"),
        "Items with no named reference rely on generic components and data only.",
    );
    out
}

#[tuff_core::watchdog]
#[test]
fn parity_matrix_is_current() {
    let root = Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../.."));
    let rendered = render(root);
    let path = root.join(OUTPUT);
    if std::env::var_os("TUFF_UPDATE_PARITY").is_some() {
        fs::write(&path, &rendered).expect("write parity matrix");
        return;
    }
    let current = fs::read_to_string(&path).unwrap_or_default();
    assert!(
        current == rendered,
        "{OUTPUT} is stale; run `TUFF_UPDATE_PARITY=1 cargo test --test server parity_matrix` and commit it"
    );
}

#[tuff_core::watchdog]
#[test]
fn name_scan_sees_known_references() {
    let root = Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../.."));
    let sources = production_sources(root);
    assert!(mentions(&sources, "EntityType::").contains("Cow"));
    assert!(mentions(&sources, "Block::").contains("Mycelium"));
}
