//! Interface mode: turns a provider's WIT package into Rust types, a wire
//! codec, typed clients and a `Serve` trait over the plugin messaging
//! layer. The host never sees this WIT; it only routes bytes.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Result, bail};
use wit_parser::{
    Function, FunctionKind, InterfaceId, Resolve, Result_, Type, TypeDef, TypeDefKind, TypeId,
    TypeOwner,
};

use crate::surface::{pascal, snake, upper};

mod cpp;

const MAX_PARAMS: usize = 6;

pub fn generate_dir(dir: &Path) -> Result<String> {
    let mut resolve = Resolve::default();
    let (package, _) = resolve.push_dir(dir)?;
    generate(&resolve, package)
}

pub fn generate_source(name: &str, source: &str) -> Result<String> {
    let mut resolve = Resolve::default();
    let package = resolve.push_str(name, source)?;
    generate(&resolve, package)
}

pub fn generate_cpp_dir(dir: &Path) -> Result<String> {
    let mut resolve = Resolve::default();
    let (package, _) = resolve.push_dir(dir)?;
    generate_cpp(&resolve, package)
}

pub fn generate_cpp_source(name: &str, source: &str) -> Result<String> {
    let mut resolve = Resolve::default();
    let package = resolve.push_str(name, source)?;
    generate_cpp(&resolve, package)
}

fn generate_cpp(resolve: &Resolve, package: wit_parser::PackageId) -> Result<String> {
    let pkg = &resolve.packages[package];
    let guard = format!(
        "TUFF_IFACE_{}_{}_HPP",
        upper(&pkg.name.namespace),
        upper(&pkg.name.name)
    );
    let mut out = format!(
        "// @generated by `tuff-plugin-sdk-gen interface`; do not edit.\n#ifndef {guard}\n#define {guard}\n\n#include \"tuff.hpp\"\n\n"
    );
    for (name, id) in &pkg.interfaces {
        let wire_name = format!("{}:{}/{}", pkg.name.namespace, pkg.name.name, name);
        Iface {
            resolve,
            id: *id,
            name,
            wire_name,
        }
        .emit_cpp(&mut out)?;
    }
    out.push_str("#endif\n");
    Ok(out)
}

fn generate(resolve: &Resolve, package: wit_parser::PackageId) -> Result<String> {
    let pkg = &resolve.packages[package];
    let mut out =
        String::from("// @generated by `tuff-plugin-sdk-gen interface`; do not edit.\n\n");
    for (name, id) in &pkg.interfaces {
        let wire_name = format!("{}:{}/{}", pkg.name.namespace, pkg.name.name, name);
        Iface {
            resolve,
            id: *id,
            name,
            wire_name,
        }
        .emit(&mut out)?;
    }
    Ok(out)
}

struct Iface<'a> {
    resolve: &'a Resolve,
    id: InterfaceId,
    name: &'a str,
    wire_name: String,
}

fn rust_ident(name: &str) -> String {
    let s = snake(name);
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern",
        "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
        "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use",
        "where", "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv",
        "try", "typeof", "unsized", "virtual", "yield",
    ];
    if KEYWORDS.contains(&s.as_str()) {
        format!("r#{s}")
    } else {
        s
    }
}

fn fnv1a(text: &str) -> u64 {
    let mut hash = 0xcbf2_9ce4_8422_2325u64;
    for byte in text.bytes() {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    hash
}

impl Iface<'_> {
    fn def(&self, id: TypeId) -> &TypeDef {
        &self.resolve.types[id]
    }

    fn type_ref(&self, ty: &Type) -> Result<String> {
        Ok(match ty {
            Type::Bool => "bool".into(),
            Type::U8 => "u8".into(),
            Type::U16 => "u16".into(),
            Type::U32 => "u32".into(),
            Type::U64 => "u64".into(),
            Type::S8 => "i8".into(),
            Type::S16 => "i16".into(),
            Type::S32 => "i32".into(),
            Type::S64 => "i64".into(),
            Type::F32 => "f32".into(),
            Type::F64 => "f64".into(),
            Type::Char => "char".into(),
            Type::String => "String".into(),
            Type::ErrorContext => bail!("error-context is not supported in plugin interfaces"),
            Type::Id(id) => {
                let def = self.def(*id);
                if let Some(name) = &def.name {
                    return Ok(match def.owner {
                        TypeOwner::Interface(owner) if owner != self.id => {
                            let owner =
                                self.resolve.interfaces[owner].name.as_deref().unwrap_or("");
                            format!("super::{}::{}", snake(owner), pascal(name))
                        }
                        _ => pascal(name),
                    });
                }
                self.anon_ref(&def.kind)?
            }
        })
    }

    fn anon_ref(&self, kind: &TypeDefKind) -> Result<String> {
        Ok(match kind {
            TypeDefKind::List(t) => format!("Vec<{}>", self.type_ref(t)?),
            TypeDefKind::Option(t) => format!("Option<{}>", self.type_ref(t)?),
            TypeDefKind::Result(r) => format!(
                "Result<{}, {}>",
                self.opt_ref(r.ok.as_ref())?,
                self.opt_ref(r.err.as_ref())?
            ),
            TypeDefKind::Tuple(t) => {
                let items: Result<Vec<_>> = t.types.iter().map(|t| self.type_ref(t)).collect();
                let items = items?;
                if items.len() == 1 {
                    format!("({},)", items[0])
                } else {
                    format!("({})", items.join(", "))
                }
            }
            TypeDefKind::Type(t) => self.type_ref(t)?,
            other => bail!("unsupported anonymous type `{}`", other.as_str()),
        })
    }

    fn opt_ref(&self, ty: Option<&Type>) -> Result<String> {
        match ty {
            Some(t) => self.type_ref(t),
            None => Ok("()".into()),
        }
    }

    fn canon(&self, ty: &Type) -> Result<String> {
        Ok(match ty {
            Type::Id(id) => self.canon_kind(&self.def(*id).kind)?,
            Type::String => "string".into(),
            other => self.type_ref(other)?,
        })
    }

    fn canon_opt(&self, ty: Option<&Type>) -> Result<String> {
        ty.map_or(Ok("_".into()), |t| self.canon(t))
    }

    fn canon_kind(&self, kind: &TypeDefKind) -> Result<String> {
        Ok(match kind {
            TypeDefKind::Record(r) => {
                let mut s = String::from("record{");
                for f in &r.fields {
                    write!(s, "{}:{},", f.name, self.canon(&f.ty)?)?;
                }
                s + "}"
            }
            TypeDefKind::Variant(v) => {
                let mut s = String::from("variant{");
                for c in &v.cases {
                    write!(s, "{}({}),", c.name, self.canon_opt(c.ty.as_ref())?)?;
                }
                s + "}"
            }
            TypeDefKind::Enum(e) => {
                let names: Vec<_> = e.cases.iter().map(|c| c.name.as_str()).collect();
                format!("enum{{{}}}", names.join(","))
            }
            TypeDefKind::Flags(f) => {
                let names: Vec<_> = f.flags.iter().map(|c| c.name.as_str()).collect();
                format!("flags{{{}}}", names.join(","))
            }
            TypeDefKind::Tuple(t) => {
                let items: Result<Vec<_>> = t.types.iter().map(|t| self.canon(t)).collect();
                format!("tuple<{}>", items?.join(","))
            }
            TypeDefKind::Option(t) => format!("option<{}>", self.canon(t)?),
            TypeDefKind::List(t) => format!("list<{}>", self.canon(t)?),
            TypeDefKind::Result(r) => format!(
                "result<{},{}>",
                self.canon_opt(r.ok.as_ref())?,
                self.canon_opt(r.err.as_ref())?
            ),
            TypeDefKind::Type(t) => self.canon(t)?,
            other => bail!("unsupported type `{}` in plugin interface", other.as_str()),
        })
    }

    fn resolve_result(&self, ty: &Type) -> Option<&Result_> {
        let Type::Id(id) = ty else { return None };
        match &self.def(*id).kind {
            TypeDefKind::Result(r) => Some(r),
            TypeDefKind::Type(t) => self.resolve_result(t),
            _ => None,
        }
    }

    fn min_size(&self, types: &[String]) -> String {
        if types.is_empty() {
            "0".into()
        } else {
            types
                .iter()
                .map(|t| format!("<{t} as Wire>::MIN_SIZE"))
                .collect::<Vec<_>>()
                .join(" + ")
        }
    }

    fn emit(&self, out: &mut String) -> Result<()> {
        let iface = &self.resolve.interfaces[self.id];
        let module = rust_ident(self.name);
        writeln!(out, "pub mod {module} {{")?;
        out.push_str(
            "    #![allow(clippy::all, unused_imports)]\n    use std::cell::RefCell;\n    use std::rc::Rc;\n\n    \
             use tuff_plugin_sdk::messaging::{CallError, Target};\n    use tuff_plugin_sdk::types::RegisterError;\n    \
             use tuff_plugin_sdk::wire::{self, Error, Wire, WireError};\n\n",
        );
        writeln!(
            out,
            "    pub const INTERFACE: &str = {:?};\n",
            self.wire_name
        )?;
        for (name, id) in &iface.types {
            self.emit_type(out, name, *id)?;
        }
        let client = pascal(self.name);
        for (name, _) in &iface.types {
            if pascal(name) == client || pascal(name) == "Serve" || pascal(name) == "Error" {
                bail!(
                    "type `{name}` collides with generated item names in `{}`",
                    self.name
                );
            }
        }
        let mut funcs = Vec::new();
        for (name, f) in &iface.functions {
            if !matches!(f.kind, FunctionKind::Freestanding) {
                bail!("`{name}`: resources and async functions are not supported");
            }
            if f.params.len() > MAX_PARAMS {
                bail!("`{name}`: at most {MAX_PARAMS} parameters are supported");
            }
            funcs.push(self.func_info(f)?);
        }
        for f in &funcs {
            writeln!(
                out,
                "    pub const {}_KEY: u64 = {:#018x};",
                upper(&f.name),
                f.key
            )?;
        }
        out.push_str(&self.emit_client(&client, &funcs)?);
        out.push_str(&self.emit_serve(&funcs));
        out.push_str("}\n\n");
        Ok(())
    }

    fn func_info(&self, f: &Function) -> Result<FuncInfo> {
        let mut params = Vec::new();
        let mut canon = Vec::new();
        for p in &f.params {
            params.push((rust_ident(&p.name), self.type_ref(&p.ty)?));
            canon.push(self.canon(&p.ty)?);
        }
        let mut signature = format!("{}#{}({})", self.wire_name, f.name, canon.join(","));
        let (ret, split) = match &f.result {
            None => ("()".to_string(), None),
            Some(ty) => {
                write!(signature, "->{}", self.canon(ty)?)?;
                let split = match self.resolve_result(ty) {
                    Some(r) if r.err.is_some() => {
                        Some((self.opt_ref(r.ok.as_ref())?, self.opt_ref(r.err.as_ref())?))
                    }
                    _ => None,
                };
                (self.type_ref(ty)?, split)
            }
        };
        Ok(FuncInfo {
            name: snake(&f.name),
            params,
            ret,
            split,
            has_result: f.result.is_some(),
            key: fnv1a(&signature),
        })
    }

    fn emit_client(&self, client: &str, funcs: &[FuncInfo]) -> Result<String> {
        let mut s = format!(
            "\n    #[derive(Debug, Clone, PartialEq)]\n    pub struct {client} {{\n        target: Target,\n    }}\n\n    \
             impl {client} {{\n        pub fn any() -> Self {{\n            Self {{ target: Target::any() }}\n        }}\n\n        \
             pub fn at(plugin: impl Into<String>) -> Self {{\n            Self {{ target: Target::plugin(plugin) }}\n        }}\n"
        );
        for f in funcs {
            let params: String = f
                .params
                .iter()
                .map(|(n, t)| format!(", {n}: {t}"))
                .collect();
            let args = f.args_tuple();
            let key = format!("{}_KEY", upper(&f.name));
            let (ret, call) = match &f.split {
                Some((ok, err)) => (
                    format!("Result<{ok}, Error<{err}>>"),
                    format!("wire::call_result::<{ok}, {err}>"),
                ),
                None => (
                    format!("Result<{}, CallError>", f.ret),
                    format!("wire::call::<{}>", f.ret),
                ),
            };
            write!(
                s,
                "\n        pub async fn {name}(&self{params}) -> {ret} {{\n            \
                 {call}(&self.target, INTERFACE, {key}, wire::encode_to_vec(&{args})).await\n        }}\n",
                name = f.name
            )?;
            if !f.has_result {
                write!(
                    s,
                    "\n        pub fn notify_{name}(&self{params}) -> Result<u32, CallError> {{\n            \
                     wire::tell(&self.target, INTERFACE, {key}, wire::encode_to_vec(&{args}))\n        }}\n",
                    name = f.name
                )?;
            }
        }
        s.push_str("    }\n");
        Ok(s)
    }

    fn emit_serve(&self, funcs: &[FuncInfo]) -> String {
        let mut s = String::from("\n    pub trait Serve {\n");
        for f in funcs {
            let params: String = f
                .params
                .iter()
                .map(|(n, t)| format!(", {n}: {t}"))
                .collect();
            let _ = writeln!(
                s,
                "        fn {}(&mut self, from: &str{params}) -> {};",
                f.name, f.ret
            );
        }
        s.push_str(
            "    }\n\n    pub fn serve<S: Serve + 'static>(imp: S) -> Result<(), RegisterError> {\n        \
             let imp = Rc::new(RefCell::new(imp));\n        tuff_plugin_sdk::messaging::provide(\n            INTERFACE,\n            vec![\n",
        );
        for f in funcs {
            let names: Vec<_> = f.params.iter().map(|(n, _)| n.as_str()).collect();
            let pattern = if names.len() == 1 {
                format!("({},)", names[0])
            } else {
                format!("({})", names.join(", "))
            };
            let types: Vec<_> = f.params.iter().map(|(_, t)| t.as_str()).collect();
            let ty = if types.len() == 1 {
                format!("({},)", types[0])
            } else {
                format!("({})", types.join(", "))
            };
            let call_args: String = names.iter().map(|n| format!(", {n}")).collect();
            let _ = writeln!(
                s,
                "                ({key}, wire::method(&imp, |__this: &mut S, __from: &str, {pattern}: {ty}| __this.{name}(__from{call_args}))),",
                key = upper(&f.name) + "_KEY",
                name = f.name
            );
        }
        s.push_str("            ],\n        )\n    }\n");
        s
    }

    fn emit_type(&self, out: &mut String, name: &str, id: TypeId) -> Result<()> {
        let def = self.def(id);
        let ty = pascal(name);
        match &def.kind {
            TypeDefKind::Record(r) => {
                let mut fields = Vec::new();
                for f in &r.fields {
                    fields.push((rust_ident(&f.name), self.type_ref(&f.ty)?));
                }
                writeln!(
                    out,
                    "    #[derive(Debug, Clone, PartialEq)]\n    pub struct {ty} {{"
                )?;
                for (n, t) in &fields {
                    writeln!(out, "        pub {n}: {t},")?;
                }
                let types: Vec<_> = fields.iter().map(|(_, t)| t.clone()).collect();
                writeln!(
                    out,
                    "    }}\n\n    impl Wire for {ty} {{\n        const MIN_SIZE: usize = {};\n        \
                     fn encode(&self, out: &mut Vec<u8>) {{",
                    self.min_size(&types)
                )?;
                for (n, _) in &fields {
                    writeln!(out, "            self.{n}.encode(out);")?;
                }
                writeln!(
                    out,
                    "            let _ = out;\n        }}\n        fn decode(input: &mut &[u8]) -> Result<Self, WireError> {{\n            Ok(Self {{"
                )?;
                for (n, _) in &fields {
                    writeln!(out, "                {n}: Wire::decode(input)?,")?;
                }
                out.push_str("            })\n        }\n    }\n\n");
            }
            TypeDefKind::Variant(v) => {
                let mut cases = Vec::new();
                for c in &v.cases {
                    let payload = c.ty.as_ref().map(|t| self.type_ref(t)).transpose()?;
                    cases.push((pascal(&c.name), payload));
                }
                writeln!(
                    out,
                    "    #[derive(Debug, Clone, PartialEq)]\n    pub enum {ty} {{"
                )?;
                for (n, p) in &cases {
                    match p {
                        Some(p) => writeln!(out, "        {n}({p}),")?,
                        None => writeln!(out, "        {n},")?,
                    }
                }
                writeln!(
                    out,
                    "    }}\n\n    impl Wire for {ty} {{\n        const MIN_SIZE: usize = 1;\n        \
                     fn encode(&self, out: &mut Vec<u8>) {{\n            match self {{"
                )?;
                for (i, (n, p)) in cases.iter().enumerate() {
                    match p {
                        Some(_) => writeln!(
                            out,
                            "                Self::{n}(v) => {{\n                    wire::write_leb(out, {i});\n                    v.encode(out);\n                }}"
                        )?,
                        None => writeln!(
                            out,
                            "                Self::{n} => wire::write_leb(out, {i}),"
                        )?,
                    }
                }
                writeln!(
                    out,
                    "            }}\n        }}\n        fn decode(input: &mut &[u8]) -> Result<Self, WireError> {{\n            \
                     match wire::read_case(input, {})? {{",
                    cases.len()
                )?;
                for (i, (n, p)) in cases.iter().enumerate() {
                    match p {
                        Some(_) => writeln!(
                            out,
                            "                {i} => Ok(Self::{n}(Wire::decode(input)?)),"
                        )?,
                        None => writeln!(out, "                {i} => Ok(Self::{n}),")?,
                    }
                }
                out.push_str(
                    "                _ => Err(WireError::BadDiscriminant),\n            }\n        }\n    }\n\n",
                );
            }
            TypeDefKind::Enum(e) => {
                let cases: Vec<_> = e.cases.iter().map(|c| pascal(&c.name)).collect();
                writeln!(
                    out,
                    "    #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n    pub enum {ty} {{"
                )?;
                for n in &cases {
                    writeln!(out, "        {n},")?;
                }
                writeln!(
                    out,
                    "    }}\n\n    impl Wire for {ty} {{\n        const MIN_SIZE: usize = 1;\n        \
                     fn encode(&self, out: &mut Vec<u8>) {{\n            wire::write_leb(out, *self as u32);\n        }}\n        \
                     fn decode(input: &mut &[u8]) -> Result<Self, WireError> {{\n            \
                     match wire::read_case(input, {})? {{",
                    cases.len()
                )?;
                for (i, n) in cases.iter().enumerate() {
                    writeln!(out, "                {i} => Ok(Self::{n}),")?;
                }
                out.push_str(
                    "                _ => Err(WireError::BadDiscriminant),\n            }\n        }\n    }\n\n",
                );
            }
            TypeDefKind::Flags(f) => {
                if f.flags.len() > 64 {
                    bail!("flags `{name}` has more than 64 members");
                }
                let mask: u64 = if f.flags.len() == 64 {
                    u64::MAX
                } else {
                    (1u64 << f.flags.len()) - 1
                };
                writeln!(
                    out,
                    "    #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]\n    pub struct {ty}(pub u64);\n\n    impl {ty} {{"
                )?;
                for (i, flag) in f.flags.iter().enumerate() {
                    writeln!(
                        out,
                        "        pub const {}: Self = Self(1 << {i});",
                        upper(&flag.name)
                    )?;
                }
                writeln!(
                    out,
                    "\n        pub fn contains(self, other: Self) -> bool {{\n            self.0 & other.0 == other.0\n        }}\n    }}\n\n    \
                     impl std::ops::BitOr for {ty} {{\n        type Output = Self;\n        fn bitor(self, rhs: Self) -> Self {{\n            Self(self.0 | rhs.0)\n        }}\n    }}\n\n    \
                     impl Wire for {ty} {{\n        const MIN_SIZE: usize = 8;\n        fn encode(&self, out: &mut Vec<u8>) {{\n            self.0.encode(out);\n        }}\n        \
                     fn decode(input: &mut &[u8]) -> Result<Self, WireError> {{\n            let bits = u64::decode(input)?;\n            \
                     if bits & !{mask:#x}u64 != 0 {{\n                return Err(WireError::BadFlags);\n            }}\n            Ok(Self(bits))\n        }}\n    }}\n"
                )?;
            }
            TypeDefKind::Type(t) => {
                writeln!(out, "    pub type {ty} = {};\n", self.type_ref(t)?)?;
            }
            TypeDefKind::Tuple(_)
            | TypeDefKind::Option(_)
            | TypeDefKind::Result(_)
            | TypeDefKind::List(_) => {
                writeln!(out, "    pub type {ty} = {};\n", self.anon_ref(&def.kind)?)?;
            }
            other => bail!(
                "type `{name}` is a {}; plugin interfaces support records, variants, enums, flags, options, results, tuples and lists only",
                other.as_str()
            ),
        }
        Ok(())
    }
}

struct FuncInfo {
    name: String,
    params: Vec<(String, String)>,
    ret: String,
    split: Option<(String, String)>,
    has_result: bool,
    key: u64,
}

impl FuncInfo {
    fn args_tuple(&self) -> String {
        let names: Vec<_> = self.params.iter().map(|(n, _)| n.as_str()).collect();
        match names.len() {
            1 => format!("({},)", names[0]),
            _ => format!("({})", names.join(", ")),
        }
    }
}
