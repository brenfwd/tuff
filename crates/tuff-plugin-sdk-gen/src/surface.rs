//! The high-level SDK surface that Rust and C++ share, generated once from
//! the plugin WIT plus the small table below: one typed marker per event
//! case (its kind flag, payload type and accessor), field accessors used by
//! event filters, and the chat colors and styles of the text builders.
//! Both languages get the same names and the same text encoding, so the
//! shared example test can compare their output byte for byte.

use std::fmt::Write as _;
use std::path::PathBuf;

use anyhow::{Context as _, Result, bail};
use wit_parser::{Resolve, Type, TypeDefKind, TypeId};

use crate::Output;

/// Chat colors by name and legacy formatting code, which the vanilla client
/// renders inside plain text.
pub const COLORS: &[(&str, char)] = &[
    ("black", '0'),
    ("dark-blue", '1'),
    ("dark-green", '2'),
    ("dark-aqua", '3'),
    ("dark-red", '4'),
    ("dark-purple", '5'),
    ("gold", '6'),
    ("gray", '7'),
    ("dark-gray", '8'),
    ("blue", '9'),
    ("green", 'a'),
    ("aqua", 'b'),
    ("red", 'c'),
    ("light-purple", 'd'),
    ("yellow", 'e'),
    ("white", 'f'),
];

/// Text styles by name and formatting code.
pub const STYLES: &[(&str, char)] = &[
    ("obfuscated", 'k'),
    ("bold", 'l'),
    ("strikethrough", 'm'),
    ("underlined", 'n'),
    ("italic", 'o'),
];

/// Timer tokens at or above this belong to each SDK's executor (`sleep`,
/// scheduled tasks); the plugin's own `schedule` tokens stay below it.
pub const TIMER_BASE: u32 = 0x4000_0000;

/// Payload fields that event filters read, and the accessor trait (Rust)
/// or function (C++) each becomes.
const FIELDS: &[(&str, &str, &str)] = &[
    ("dimension", "HasDimension", "dimension_of"),
    ("state", "HasState", "state_of"),
    ("player", "HasPlayer", "player_of"),
];

struct Case {
    /// The WIT case name, such as `block-break`.
    name: String,
    /// The payload record's WIT name, such as `block-change`.
    payload: String,
    payload_id: TypeId,
}

fn words(name: &str) -> impl Iterator<Item = &str> {
    name.split('-').filter(|w| !w.is_empty())
}

pub(crate) fn pascal(name: &str) -> String {
    words(name)
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

pub(crate) fn upper(name: &str) -> String {
    name.replace('-', "_").to_ascii_uppercase()
}

pub(crate) fn snake(name: &str) -> String {
    name.replace('-', "_")
}

fn types_interface(resolve: &Resolve) -> Result<wit_parser::InterfaceId> {
    resolve
        .interfaces
        .iter()
        .find(|(_, i)| i.name.as_deref() == Some("types"))
        .map(|(id, _)| id)
        .context("no `types` interface")
}

fn named(resolve: &Resolve, name: &str) -> Result<TypeId> {
    let types = types_interface(resolve)?;
    resolve.interfaces[types]
        .types
        .get(name)
        .copied()
        .with_context(|| format!("no type `{name}` in `types`"))
}

fn cases(resolve: &Resolve) -> Result<Vec<Case>> {
    let event = named(resolve, "event")?;
    let TypeDefKind::Variant(variant) = &resolve.types[event].kind else {
        bail!("`event` is not a variant");
    };
    let mut out = Vec::new();
    for case in &variant.cases {
        let Some(Type::Id(id)) = case.ty else {
            bail!("event case `{}` has no record payload", case.name);
        };
        let payload = resolve.types[id]
            .name
            .clone()
            .with_context(|| format!("event case `{}` has an anonymous payload", case.name))?;
        out.push(Case {
            name: case.name.clone(),
            payload,
            payload_id: id,
        });
    }
    Ok(out)
}

/// How record `id` exposes `field`: `None` when it has no such field,
/// `Some(true)` when the field is optional.
fn field(resolve: &Resolve, id: TypeId, field: &str) -> Option<bool> {
    let TypeDefKind::Record(record) = &resolve.types[id].kind else {
        return None;
    };
    let f = record.fields.iter().find(|f| f.name == field)?;
    match f.ty {
        Type::Id(inner) => Some(matches!(resolve.types[inner].kind, TypeDefKind::Option(_))),
        _ => Some(false),
    }
}

/// Distinct payload records in case order.
fn payloads(cases: &[Case]) -> Vec<&Case> {
    let mut seen: Vec<&Case> = Vec::new();
    for case in cases {
        if !seen.iter().any(|c| c.payload_id == case.payload_id) {
            seen.push(case);
        }
    }
    seen
}

const HEADER: &str = "Generated by tuff-plugin-sdk-gen from crates/tuff-plugin-wasm/wit and \
crates/tuff-plugin-sdk-gen/src/surface.rs; do not edit. Regenerate with \
`cargo run -p tuff-plugin-sdk-gen`.";

fn rust(resolve: &Resolve, cases: &[Case]) -> Result<String> {
    let mut s = String::new();
    writeln!(s, "// {HEADER}")?;
    s.push_str(
        "\nuse crate::events::{Case, HasDimension, HasPlayer, HasState};\n\
         use crate::text::Span;\n\
         use crate::types::{self, Event, EventKinds};\n\n",
    );
    writeln!(
        s,
        "/// Timer tokens at or above this are the executor's own.\npub const TIMER_BASE: u32 = {TIMER_BASE:#x};\n"
    )?;
    s.push_str("/// One marker type per event case, for [`crate::events::on`].\npub mod ev {\n");
    for case in cases {
        writeln!(
            s,
            "    /// `{}` events, carrying a [`crate::types::{}`].\n    pub struct {};\n",
            case.name,
            pascal(&case.payload),
            pascal(&case.name)
        )?;
    }
    s.truncate(s.len() - 1);
    s.push_str("}\n\n");
    for case in cases {
        let (marker, payload, flag) =
            (pascal(&case.name), pascal(&case.payload), upper(&case.name));
        writeln!(
            s,
            "impl Case for ev::{marker} {{\n    \
             const KIND: EventKinds = EventKinds::{flag};\n    \
             type Payload = types::{payload};\n\n    \
             fn get(event: &Event) -> Option<&types::{payload}> {{\n        \
             match event {{\n            \
             Event::{marker}(payload) => Some(payload),\n            \
             _ => None,\n        \
             }}\n    \
             }}\n}}\n"
        )?;
    }
    s.push_str("/// The kind flag of `event`.\npub fn kind(event: &Event) -> EventKinds {\n    match event {\n");
    for case in cases {
        writeln!(
            s,
            "        Event::{}(_) => EventKinds::{},",
            pascal(&case.name),
            upper(&case.name)
        )?;
    }
    s.push_str("    }\n}\n");
    for case in payloads(cases) {
        let payload = pascal(&case.payload);
        if case.payload == "player" {
            writeln!(
                s,
                "\nimpl HasPlayer for types::Player {{\n    \
                 fn player(&self) -> Option<&types::Player> {{\n        Some(self)\n    }}\n}}"
            )?;
            continue;
        }
        for &(name, rust_trait, _) in FIELDS {
            match (name, field(resolve, case.payload_id, name)) {
                (_, None) => {}
                ("player", Some(optional)) => {
                    let body = if optional {
                        "self.player.as_ref()"
                    } else {
                        "Some(&self.player)"
                    };
                    writeln!(
                        s,
                        "\nimpl {rust_trait} for types::{payload} {{\n    \
                         fn player(&self) -> Option<&types::Player> {{\n        {body}\n    }}\n}}"
                    )?;
                }
                (name, Some(_)) => writeln!(
                    s,
                    "\nimpl {rust_trait} for types::{payload} {{\n    \
                     fn {name}(&self) -> &str {{\n        &self.{name}\n    }}\n}}"
                )?,
            }
        }
    }
    let palette = |s: &mut String, kind: &str, doc: &str, table: &[(&str, char)]| -> Result<()> {
        writeln!(
            s,
            "\n/// {doc}\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum {kind} {{"
        )?;
        for (name, _) in table {
            writeln!(s, "    {},", pascal(name))?;
        }
        writeln!(
            s,
            "}}\n\nimpl {kind} {{\n    pub const ALL: [{kind}; {}] = [",
            table.len()
        )?;
        for (name, _) in table {
            writeln!(s, "        {kind}::{},", pascal(name))?;
        }
        s.push_str("    ];\n\n    /// The formatting code after the section sign.\n    pub const fn code(self) -> char {\n        match self {\n");
        for (name, code) in table {
            writeln!(s, "            {kind}::{} => '{code}',", pascal(name))?;
        }
        s.push_str("        }\n    }\n}\n");
        Ok(())
    };
    palette(&mut s, "Color", "A chat color.", COLORS)?;
    palette(&mut s, "Style", "A text style.", STYLES)?;
    s.push_str(
        "\n/// Styling for text: `\"hi\".gold()`, `name.aqua()` (also on a `String`, without\n\
         /// moving it). A [`Span`] has the same methods to chain: `.gold().bold()`.\n\
         pub trait Styled {\n    \
         fn color(&self, color: Color) -> Span;\n\n    \
         fn style(&self, style: Style) -> Span;\n",
    );
    let methods = |s: &mut String, receiver: &str, vis: &str| -> Result<()> {
        for (name, _) in COLORS {
            writeln!(
                s,
                "\n    {vis}fn {}({receiver}) -> Span {{\n        self.color(Color::{})\n    }}",
                snake(name),
                pascal(name)
            )?;
        }
        for (name, _) in STYLES {
            writeln!(
                s,
                "\n    {vis}fn {}({receiver}) -> Span {{\n        self.style(Style::{})\n    }}",
                snake(name),
                pascal(name)
            )?;
        }
        Ok(())
    };
    methods(&mut s, "&self", "")?;
    s.push_str("}\n\nimpl Span {\n");
    s.push_str(
        "    pub fn color(self, color: Color) -> Span {\n        self.with_color(color)\n    }\n\n    \
         pub fn style(self, style: Style) -> Span {\n        self.with_style(style)\n    }\n",
    );
    methods(&mut s, "self", "pub ")?;
    s.push_str("}\n");
    Ok(s)
}

fn c_type(name: &str) -> String {
    format!("raw::tuff_plugin_types_{}_t", snake(name))
}

fn cpp(resolve: &Resolve, cases: &[Case]) -> Result<String> {
    let mut s = String::new();
    writeln!(s, "// {HEADER}")?;
    s.push_str(
        "#ifndef TUFF_GEN_HPP\n#define TUFF_GEN_HPP\n\n#include \"tuff/base.hpp\"\n\nnamespace tuff {\n\n",
    );
    writeln!(
        s,
        "// Timer tokens at or above this are the executor's own.\ninline constexpr uint32_t timer_base = {TIMER_BASE:#x}u;\n"
    )?;
    s.push_str("// One marker per event case, for tuff::on<ev::Join>(...).\nnamespace ev {\n");
    for case in cases {
        let (shout, field) = (upper(&case.name), snake(&case.name));
        writeln!(
            s,
            "struct {} {{\n    \
             using payload = {};\n    \
             static constexpr raw::tuff_event_kinds_t kind = TUFF_PLUGIN_TYPES_EVENT_KINDS_{shout};\n    \
             static const payload *get(const raw::tuff_event_t *ev) {{\n        \
             return ev->tag == TUFF_PLUGIN_TYPES_EVENT_{shout} ? &ev->val.{field} : nullptr;\n    \
             }}\n}};",
            pascal(&case.name),
            c_type(&case.payload)
        )?;
    }
    s.push_str("} // namespace ev\n\n// Payload fields that event filters read.\n");
    for case in payloads(cases) {
        let payload = c_type(&case.payload);
        if case.payload == "player" {
            writeln!(
                s,
                "inline const raw::tuff_player_t *player_of(const {payload} &p) {{ return &p; }}"
            )?;
            continue;
        }
        for &(name, _, function) in FIELDS {
            match (name, field(resolve, case.payload_id, name)) {
                (_, None) => {}
                ("player", Some(true)) => writeln!(
                    s,
                    "inline const raw::tuff_player_t *{function}(const {payload} &p) {{ return p.player.is_some ? &p.player.val : nullptr; }}"
                )?,
                ("player", Some(false)) => writeln!(
                    s,
                    "inline const raw::tuff_player_t *{function}(const {payload} &p) {{ return &p.player; }}"
                )?,
                (name, Some(_)) => writeln!(
                    s,
                    "inline Str {function}(const {payload} &p) {{ return p.{name}; }}"
                )?,
            }
        }
    }
    let palette = |s: &mut String, kind: &str, table: &[(&str, char)]| -> Result<()> {
        writeln!(s, "\nenum class {kind} : char {{")?;
        for (name, code) in table {
            writeln!(s, "    {} = '{code}',", pascal(name))?;
        }
        s.push_str("};\n");
        Ok(())
    };
    palette(&mut s, "Color", COLORS)?;
    palette(&mut s, "Style", STYLES)?;
    s.push_str("\n// The order a span's style codes are written in.\ninline constexpr Style styles_in_order[] = {");
    for (i, (name, _)) in STYLES.iter().enumerate() {
        let sep = if i == 0 { "" } else { ", " };
        write!(s, "{sep}Style::{}", pascal(name))?;
    }
    s.push_str(
        "};\n\n\
         // Text in one color and set of styles, borrowing its text: tuff::gold(\"hi\").bold().\n\
         class Span {\n  \
         public:\n    \
         Span(const char *text) : text_(raw::tuff_str(text)) {}\n    \
         Span(Str text) : text_(text) {}\n    \
         // Anything with a view(), such as Text and String.\n    \
         template <class T> Span(const T &text) : text_(text.view()) {}\n\n    \
         Span color(Color c) const {\n        Span s = *this;\n        s.color_ = static_cast<char>(c);\n        return s;\n    }\n    \
         Span style(Style st) const {\n        Span s = *this;\n        s.styles_ |= bit(st);\n        return s;\n    }\n",
    );
    for (name, _) in COLORS {
        writeln!(
            s,
            "    Span {}() const {{ return color(Color::{}); }}",
            snake(name),
            pascal(name)
        )?;
    }
    for (name, _) in STYLES {
        writeln!(
            s,
            "    Span {}() const {{ return style(Style::{}); }}",
            snake(name),
            pascal(name)
        )?;
    }
    s.push_str(
        "\n    Str text() const { return text_; }\n    \
         // The color code, 0 for none.\n    \
         char color_code() const { return color_; }\n    \
         bool has(Style st) const { return (styles_ & bit(st)) != 0; }\n\n  \
         private:\n    \
         static uint8_t bit(Style st) {\n        \
         for (unsigned i = 0; i < sizeof styles_in_order; i++) {\n            \
         if (styles_in_order[i] == st) {\n                return static_cast<uint8_t>(1u << i);\n            }\n        }\n        \
         return 0;\n    }\n\n    \
         Str text_;\n    \
         char color_ = 0;\n    \
         uint8_t styles_ = 0;\n};\n\n",
    );
    for (name, _) in COLORS.iter().chain(STYLES) {
        writeln!(
            s,
            "template <class T> Span {0}(const T &text) {{ return Span(text).{0}(); }}",
            snake(name)
        )?;
    }
    s.push_str("\n} // namespace tuff\n\n#endif\n");
    Ok(s)
}

/// `crates/tuff-plugin-sdk/c/tuff/unraw.hpp`, which tuff.hpp includes last to
/// undefine the constants the C bindings (`plugin_h`) define as macros.
pub fn unraw(plugin_h: &str) -> Result<Output> {
    let mut s = String::new();
    writeln!(s, "// {HEADER}")?;
    for line in plugin_h.lines() {
        let Some(name) = line.strip_prefix("#define ") else {
            continue;
        };
        let name = name.split_whitespace().next().unwrap_or_default();
        if !name.starts_with("__") {
            writeln!(s, "#undef {name}")?;
        }
    }
    Ok(Output {
        path: PathBuf::from("crates/tuff-plugin-sdk/c/tuff/unraw.hpp"),
        contents: s.into_bytes(),
    })
}

/// `crates/tuff-plugin-sdk/src/generated.rs` and `crates/tuff-plugin-sdk/c/tuff_gen.hpp`.
pub fn generate(resolve: &Resolve) -> Result<Vec<Output>> {
    let cases = cases(resolve)?;
    Ok(vec![
        Output {
            path: PathBuf::from("crates/tuff-plugin-sdk/src/generated.rs"),
            contents: rust(resolve, &cases)?.into_bytes(),
        },
        Output {
            path: PathBuf::from("crates/tuff-plugin-sdk/c/tuff_gen.hpp"),
            contents: cpp(resolve, &cases)?.into_bytes(),
        },
    ])
}
